--
-- نوع بروزرسانی را «خود اپ» از روی ارقام نسخه تشخیص می‌دهد:
--   ▸ تغییر رقم اول  (6→7): آپدیت اصلی  → اجباری (دیالوگ غیرقابل‌رد + اعلان پایدار)
--   ▸ تغییر رقم وسط (3→4): تغییرات جزیی → اختیاری، اعلان در هر بار اجرا + تایید کاربر
--   ▸ تغییر رقم آخر (1→2): بهبود/رفع باگ → فقط بنر متنی خود-حذف در استارت، روزی یک‌بار
--
-- مراحل انتشار هر نسخه:
--   ۱) فایل APK امضاشده را در Storage → باکت «app_releases» آپلود کنید.
--   ۲) یکی از قالب‌های زیر را (با مقادیر نسخه خودتان) در SQL Editor اجرا کنید.
-- ============================================================================


